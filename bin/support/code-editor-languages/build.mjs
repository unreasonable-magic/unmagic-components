// Run npm ci --ignore-scripts, then node build.mjs in this directory.
// Bundles only language implementations. The existing editor core stays shared.
import { build } from 'esbuild'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, resolve, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const vendor = resolve(root, '../../../app/assets/javascripts/unmagic/components/code_editor/vendor')
const namespace = 'unmagic/components/code_editor/vendor/'
const shared = new Set([
  '@codemirror/autocomplete', '@codemirror/language', '@codemirror/state', '@codemirror/view',
  '@lezer/common', '@lezer/highlight', '@lezer/lr',
])
const languages = ['javascript', 'python', 'html', 'css', 'sql', 'java', 'cpp', 'go']
const entries = languages.map(language => [`@codemirror/lang-${language}`, `@codemirror--lang-${language}.js`])
entries.push(['@codemirror/legacy-modes/mode/ruby', '@codemirror--legacy-ruby.js'])
const bundledPackages = new Map()
for (const [entry, filename] of entries) {
  const packageName = entry.startsWith('@codemirror/legacy') ? '@codemirror/legacy-modes' : entry
  const version = JSON.parse(readFileSync(resolve(root, 'node_modules', packageName, 'package.json'))).version
  const result = await build({
    absWorkingDir: root,
    stdin: { contents: `export * from ${JSON.stringify(entry)}`, resolveDir: root },
    bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true,
    outfile: resolve(vendor, filename), metafile: true, legalComments: 'inline',
    banner: { js: `// ${entry}@${version}; generated by bin/support/code-editor-languages/build.mjs` },
    plugins: [{ name: 'shared-editor-core', setup(build) {
      build.onResolve({ filter: /^@(?:codemirror|lezer)\// }, args => {
        if (shared.has(args.path)) return { path: namespace + args.path.replace('/', '--'), external: true }
      })
    }}],
  })
  for (const input of Object.keys(result.metafile.inputs)) {
    if (!input.startsWith('node_modules/')) continue
    let directory = dirname(resolve(root, input))
    while (directory !== root && !existsSync(resolve(directory, 'package.json'))) directory = dirname(directory)
    const pkg = JSON.parse(readFileSync(resolve(directory, 'package.json')))
    if (!bundledPackages.has(pkg.name)) {
      const license = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'License.txt'].map(file => resolve(directory, file)).find(existsSync)
      if (!license) throw new Error(`Missing license for ${pkg.name}`)
      bundledPackages.set(pkg.name, `${pkg.name}@${pkg.version}\nhttps://www.npmjs.com/package/${pkg.name}/v/${pkg.version}\n\n${readFileSync(license, 'utf8')}`)
    }
  }
  console.log(relative(resolve(root, '../../..'), resolve(vendor, filename)))
}
writeFileSync(resolve(vendor, 'LICENSES-languages.txt'), [...bundledPackages.entries()].sort().map(([, text]) => text).join('\n\n'))
